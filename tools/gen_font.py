def main():
    os.makedirs(OUT, exist_ok=True)
    chars = sorted(G.keys(), key=ord)
    cols = 16
    cw, chh = 8, ROWS + 1
    rows = (len(chars) + cols - 1) // cols
    W, H = cols * cw, rows * chh
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    lines = []
    for i, ch in enumerate(chars):
        glyph = G[ch]
        w = max(len(r) for r in glyph)
        gx, gy = (i % cols) * cw, (i // cols) * chh
        for y, row in enumerate(glyph):
            for x, px in enumerate(row):
                if px == "#":
                    img.putpixel((gx + x, gy + y), (255, 255, 255, 255))
        adv = w + 1
        lines.append(f"char id={ord(ch)} x={gx} y={gy} width={w} height={ROWS} "
                     f"xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15")
    img.save(os.path.join(OUT, "orion_pixel.png"))
    head = [
        'info face="Orion 5x7" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 '
        'smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight={LINE} base={BASE} scaleW={W} scaleH={H} pages=1 packed=0 "
        "alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4",
        'page id=0 file="orion_pixel.png"',
        f"chars count={len(chars)}",
    ]
    with open(os.path.join(OUT, "orion_pixel.fnt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(head + lines) + "\n")
    print(f"{len(chars)} glyphs -> art/fonts/orion_pixel.fnt ({W}x{H} atlas)")


if __name__ == "__main__":
    main()
